"""Analyser (and synthetic-data generator) for campus 2.4 GHz survey CSVs written by wifi_survey.sh.

INPUT CSV: lines starting with '#' are comments (a comment containing the word SYNTHETIC marks the data as synthetic and that flag is carried into
every output); columns timestamp,scan_id,channel,freq_mhz,signal_pct,signal_dbm_est; channel 0 = a scan that saw no 2.4 GHz AP. No SSID/BSSID exists.

WHAT IT COMPUTES
- per channel 1..13: mean APs per scan, mean strong (>= -70 dBm) APs per scan, mean signal, share of scans with >= 1 AP;
- three-non-overlapping-channel view: every AP assigned to the nearest of channels 1/6/11 (1-3 -> 1, 4-8 -> 6, 9-13 -> 11); APs that sit on a
  channel other than 1/6/11 are counted separately because they overlap two of the three;
- overlap-aware exposure: an AP on channel c touches hop channel k with weight w = max(0, 1 - 5|c-k|/22) (triangular approximation of the
  22 MHz-wide Wi-Fi spectrum mask against a NARROW hopping signal on a 5 MHz grid; adjacent-channel leakage beyond 22 MHz is ignored);
- effective number of channels for hopping over the 13 grid channels, from the per-channel availability a_k = 1 - loss_k:
    M_eff_sum = sum a_k (how many channel-equivalents deliver), M_eff_ipr = (sum a_k)^2 / sum a_k^2 (shrinks when good channels are few/concentrated),
    M_orth = 3 (channels 1/6/11, the number of mutually non-overlapping 22 MHz Wi-Fi channels), and M_indep_span = (60 MHz + 22 MHz)/22 MHz = 3.7 (independent 22 MHz slots in the 13-channel grid) and
    'channel-equivalents shadowed per AP' = sum_k w(c,k) = 4.5 for a mid-band AP (9 of 13 grid channels get w > 0): against Wi-Fi the 13 hop channels do NOT act as 13 independent ones;
- time-of-day pattern: mean APs per scan and mean M_eff_sum per local hour (hour = digits 11-12 of the timestamp);
- PER-CHANNEL LOSS PROBABILITY JSON for the simulator (see MAPPING).

MAPPING (an ASSUMPTION, not a measurement - the survey measures presence and strength, not airtime):
  per AP observation i in a scan: s_i = clip((dBm_i + 90) / 30, 0, 1)   (-90 dBm or weaker -> 0, -60 dBm or stronger -> 1)
  a frame of ours on channel k is lost with probability  q_k(scan) = 1 - prod_i (1 - u * w(c_i,k) * s_i)
  where u = assumed airtime duty of one AP (default 0.10 via --u) ; loss_k = p_floor + (1 - p_floor) * mean_over_scans q_k  with p_floor = 0.01 (sim 'p_clean').
  Capped at p_cap = 0.95 (sim 'p_jam'). u must be calibrated against real packet loss measurements before the JSON is trusted.
  JSON keys: synthetic, source, n_scans, mapping, params, loss_by_channel {"1":..,"13":..}, loss_by_hour {"HH": [13 numbers]} (hours that have >= 3 scans), m_eff.
CLI:
  python3 wifi_survey.py synthesize [--out synthetic_wifi_survey.csv] [--seed 1]
  python3 wifi_survey.py analyse CSV [--json out.json] [--fig out.png] [--u 0.10]
  python3 wifi_survey.py            (demo: synthesise if absent, analyse, write JSON + figure)
"""
import os, sys, csv, json, math, argparse
import numpy as np

CH = list(range(1, 14)); STRONG = -70.0; P_FLOOR, P_CAP = 0.01, 0.95
HERE = os.path.dirname(os.path.abspath(__file__))


def freq(ch): return 2484 if ch == 14 else 2407 + 5 * ch
def overlap(c, k): return max(0.0, 1.0 - 5.0 * abs(c - k) / 22.0)


# ------------------------------------------------------------------ synthetic data
def synthesize(path, seed=1, days=3, minutes=10, n_aps=36):
    """SYNTHETIC campus: fixed APs (1/6/11 heavy) + personal hotspots that appear only in the day, with 3 dB fading. Not a real measurement."""
    rng = np.random.default_rng(seed)
    chans = rng.choice([1, 6, 11, 2, 3, 4, 5, 7, 8, 9, 10], n_aps, p=[.22, .26, .20, .03, .03, .03, .03, .06, .05, .05, .04])
    base = rng.uniform(-88, -45, n_aps); hotspot = rng.random(n_aps) < 0.35; peak_h = rng.uniform(11, 17, n_aps)
    rows = []
    for d in range(days):
        for step in range(0, 24 * 60, minutes):
            hh, mm = divmod(step, 60); sid = f"syn-{d:02d}{step:04d}"; ts = f"2026-09-{14+d:02d}T{hh:02d}:{mm:02d}:00+0530"; seen = 0
            for i in range(n_aps):
                if hotspot[i]:   # personal hotspot / laptop AP: present with a daytime bump (8-22 h), rare at night
                    p_on = 0.85 * math.exp(-((hh + mm / 60 - peak_h[i]) / 4.0) ** 2) * (1 if 8 <= hh < 22 else 0.15)
                else: p_on = 0.97 if 8 <= hh < 20 else 0.9
                if rng.random() > p_on: continue
                dbm = base[i] + rng.normal(0, 3) + (2.0 if 9 <= hh < 17 and not hotspot[i] else 0.0)
                if dbm < -92: continue
                pct = int(min(100, max(0, round(2 * (dbm + 100))))); rows.append((ts, sid, int(chans[i]), freq(int(chans[i])), pct, pct / 2 - 100)); seen += 1
            if seen == 0: rows.append((ts, sid, 0, 0, 0, -100.0))
    with open(path, "w") as f:
        f.write(f"# SYNTHETIC DATA: generated by lab3/wifi_survey.py synthesize (seed={seed}); {n_aps} fake APs, {days} days, one scan per {minutes} min. NOT a real measurement.\n")
        f.write("timestamp,scan_id,channel,freq_mhz,signal_pct,signal_dbm_est\n")
        for r in rows: f.write(f"{r[0]},{r[1]},{r[2]},{r[3]},{r[4]},{r[5]:.1f}\n")
    return len(rows)


# ------------------------------------------------------------------ reading
def read_csv(path):
    synthetic = False; header_seen = False; scans = {}; order = []
    with open(path, newline="") as f:
        for line in f:
            if line.startswith("#"):
                synthetic |= "SYNTHETIC" in line.upper(); continue
            if not line.strip(): continue
            if not header_seen:
                if not line.startswith("timestamp"): raise ValueError("missing header line 'timestamp,scan_id,...'")
                header_seen = True; continue
            p = line.strip().split(",")
            if len(p) < 6: continue
            try: ts, sid, ch, fr, pct, dbm = p[0], p[1], int(p[2]), int(p[3]), int(float(p[4])), float(p[5])
            except ValueError: continue
            if sid not in scans: scans[sid] = dict(ts=ts, hour=int(ts[11:13]) if len(ts) >= 13 and ts[11:13].isdigit() else -1, aps=[]); order.append(sid)
            if ch >= 1: scans[sid]["aps"].append((ch, dbm))
    return synthetic, [scans[s] for s in order]


# ------------------------------------------------------------------ analysis
def loss_per_scan(aps, u):
    """vector over CH of q_k for one scan (see MAPPING)."""
    keep = np.ones(len(CH))
    for c, dbm in aps:
        s = min(1.0, max(0.0, (dbm + 90.0) / 30.0))
        for j, k in enumerate(CH): keep[j] *= 1.0 - u * overlap(c, k) * s
    return 1.0 - keep


def analyse(scans, u=0.10):
    n = len(scans); res = dict(n_scans=n)
    cnt = np.zeros(14); strong = np.zeros(14); sig = [[] for _ in range(14)]; present = np.zeros(14)
    for sc in scans:
        seen = set()
        for c, d in sc["aps"]:
            if 1 <= c <= 13: cnt[c] += 1; strong[c] += d >= STRONG; sig[c].append(d); seen.add(c)
        for c in seen: present[c] += 1
    res["per_channel"] = {c: dict(aps_per_scan=cnt[c] / n, strong_per_scan=strong[c] / n, mean_dbm=float(np.mean(sig[c])) if sig[c] else None, scans_with_ap=present[c] / n) for c in CH}
    grp = {1: 0.0, 6: 0.0, 11: 0.0}; other = 0.0
    for c in CH:
        g = 1 if c <= 3 else 6 if c <= 8 else 11; grp[g] += cnt[c] / n
        if c not in (1, 6, 11): other += cnt[c] / n
    res["view_1_6_11"] = dict(aps_per_scan=grp, share_on_non_1_6_11=other / max(sum(grp.values()), 1e-9))
    Q = np.array([loss_per_scan(sc["aps"], u) for sc in scans]); loss = np.minimum(P_CAP, P_FLOOR + (1 - P_FLOOR) * Q.mean(0))
    a = 1 - loss; res["loss_by_channel"] = {str(c): float(loss[i]) for i, c in enumerate(CH)}
    res["m_eff"] = dict(M=len(CH), M_orth=3, M_eff_sum=float(a.sum()), M_eff_ipr=float(a.sum() ** 2 / (a ** 2).sum()), mean_loss=float(loss.mean()),
                        shadowed_channel_equivalents_per_AP_mid=float(sum(overlap(7, k) for k in CH)), M_indep_span=(60 + 22) / 22)
    hours = {}
    for h in range(24):
        idx = [i for i, sc in enumerate(scans) if sc["hour"] == h]
        if len(idx) >= 3:
            lh = np.minimum(P_CAP, P_FLOOR + (1 - P_FLOOR) * Q[idx].mean(0)); ah = 1 - lh
            hours[h] = dict(n_scans=len(idx), aps_per_scan=float(np.mean([len(scans[i]["aps"]) for i in idx])), strong_per_scan=float(np.mean([sum(d >= STRONG for _, d in scans[i]["aps"]) for i in idx])),
                            m_eff_sum=float(ah.sum()), mean_loss=float(lh.mean()), loss=[float(x) for x in lh])
    res["by_hour"] = hours; res["u"] = u
    return res


def to_json(res, synthetic, source):
    return dict(synthetic=bool(synthetic), source=source, n_scans=res["n_scans"],
                mapping="loss_k = 0.01 + 0.99 * mean over scans of [1 - prod_over_APs(1 - u * w(c_i,k) * s_i)], w = max(0, 1-5|c-k|/22), s = clip((dBm+90)/30,0,1), capped at 0.95; "
                        "ASSUMPTION: u = airtime duty per AP; presence/strength survey does not measure airtime, calibrate u against real packet loss",
                params=dict(u=res["u"], p_floor=P_FLOOR, p_cap=P_CAP, strong_dbm=STRONG), loss_by_channel=res["loss_by_channel"],
                loss_by_hour={f"{h:02d}": v["loss"] for h, v in res["by_hour"].items()}, m_eff=res["m_eff"])


def report(res, synthetic):
    tag = "[SYNTHETIC DATA] " if synthetic else ""
    print(f"{tag}{res['n_scans']} scans")
    print(f"{'ch':>3s} {'APs/scan':>9s} {'strong/scan':>11s} {'mean dBm':>9s} {'scans w/ AP':>11s} {'loss (u=%.2f)' % res['u']:>13s}")
    for c in CH:
        p = res["per_channel"][c]; print(f"{c:3d} {p['aps_per_scan']:9.2f} {p['strong_per_scan']:11.2f} {p['mean_dbm'] if p['mean_dbm'] is not None else float('nan'):9.1f} {p['scans_with_ap']:11.2f} {res['loss_by_channel'][str(c)]:13.3f}")
    v = res["view_1_6_11"]; print("1/6/11 view (APs per scan):", {k: round(float(x), 2) for k, x in v["aps_per_scan"].items()}, f"; share of APs on other channels: {v['share_on_non_1_6_11']:.2f}")
    m = res["m_eff"]; print(f"effective channels for hopping over {m['M']} grid channels: M_eff_sum={m['M_eff_sum']:.2f}, M_eff_ipr={m['M_eff_ipr']:.2f}, M_orth (non-overlapping Wi-Fi) = {m['M_orth']}, mean loss {m['mean_loss']:.3f}; "
          f"M_indep_span={m['M_indep_span']:.1f}; one mid-band AP shadows {m['shadowed_channel_equivalents_per_AP_mid']:.2f} channel-equivalents of the 13 (triangular overlap)")
    print("time of day (hour: APs/scan, strong/scan, M_eff_sum, mean loss):")
    for h, x in res["by_hour"].items(): print(f"  {h:02d}h: {x['aps_per_scan']:5.1f} {x['strong_per_scan']:5.1f} {x['m_eff_sum']:6.2f} {x['mean_loss']:.3f}")


def figure(res, synthetic, path):
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    fig, ax = plt.subplots(1, 3, figsize=(14, 4)); x = np.array(CH)
    ax[0].bar(x - .2, [res["per_channel"][c]["aps_per_scan"] for c in CH], .4, label="all APs"); ax[0].bar(x + .2, [res["per_channel"][c]["strong_per_scan"] for c in CH], .4, label="strong (>= -70 dBm)")
    ax[0].set_xlabel("channel"); ax[0].set_ylabel("APs per scan"); ax[0].legend(); ax[0].set_xticks(CH); ax[0].set_title("Occupancy per channel")
    ax[1].bar(x, [res["loss_by_channel"][str(c)] for c in CH], color="C3"); ax[1].set_xlabel("channel"); ax[1].set_ylabel("assumed loss probability"); ax[1].set_xticks(CH); ax[1].set_title(f"Loss map (u={res['u']}, assumption)")
    hs = list(res["by_hour"]); ax[2].plot(hs, [res["by_hour"][h]["aps_per_scan"] for h in hs], "o-", label="APs/scan"); ax2 = ax[2].twinx(); ax2.plot(hs, [res["by_hour"][h]["m_eff_sum"] for h in hs], "s--", color="C2", label="M_eff_sum")
    ax[2].set_xlabel("local hour"); ax[2].set_ylabel("APs per scan"); ax2.set_ylabel("M_eff (sum)"); ax[2].set_title("Time of day")
    fig.suptitle(("SYNTHETIC DATA - " if synthetic else "") + "2.4 GHz survey analysis", color="C3" if synthetic else "k"); fig.tight_layout(); fig.savefig(path, dpi=120); plt.close(fig)


def main(argv=None):
    ap = argparse.ArgumentParser(description="2.4 GHz survey analyser"); sub = ap.add_subparsers(dest="cmd")
    s = sub.add_parser("synthesize"); s.add_argument("--out", default=os.path.join(HERE, "synthetic_wifi_survey.csv")); s.add_argument("--seed", type=int, default=1)
    a_ = sub.add_parser("analyse"); a_.add_argument("csv"); a_.add_argument("--json"); a_.add_argument("--fig"); a_.add_argument("--u", type=float, default=0.10)
    a = ap.parse_args(argv)
    if a.cmd == "synthesize": print(f"wrote {synthesize(a.out, a.seed)} rows to {a.out} (SYNTHETIC)"); return 0
    if a.cmd is None:
        csvp = os.path.join(HERE, "synthetic_wifi_survey.csv")
        if not os.path.exists(csvp): print(f"synthesised {synthesize(csvp)} rows -> {csvp}")
        a = argparse.Namespace(csv=csvp, json=os.path.join(HERE, "synthetic_channel_loss.json"), fig=os.path.join(HERE, "figures", "wifi_survey.png"), u=0.10)
    synthetic, scans = read_csv(a.csv)
    if not scans: print("no scans in file", file=sys.stderr); return 2
    res = analyse(scans, a.u); report(res, synthetic)
    if a.json: json.dump(to_json(res, synthetic, os.path.basename(a.csv)), open(a.json, "w"), indent=1); print("wrote", a.json)
    if a.fig: figure(res, synthetic, a.fig); print("wrote", a.fig)
    return 0


if __name__ == "__main__":
    sys.exit(main())
